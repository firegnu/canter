use crate::*;
use schemars::{JsonSchema, SchemaGenerator};
use std::{fs, path::Path};
use ts_rs::{Config, TS};

/// Regenerate the schema catalog (`#/$defs/<Type>`) and TypeScript declarations.
/// Configuration is explicit so ambient TS_RS_* variables cannot change output.
pub fn export_protocol(directory: &Path) -> Result<(), Box<dyn std::error::Error>> {
    fs::create_dir_all(directory)?;
    let config = Config::new().with_out_dir(directory.join("typescript"));
    let mut schemas = SchemaGenerator::default();
    macro_rules! export {
        ($($ty:ty),+ $(,)?) => {$(export_type::<$ty>(&mut schemas, &config)?;)+};
    }
    export!(
        Event,
        EventPayload,
        ErrorResponse,
        SessionSnapshot,
        SessionSummary,
        SessionPath,
        RequestPath,
        InfoParams,
        InfoResponse,
        ModelListParams,
        ModelListResponse,
        UsageResponse,
        ContextResponse,
        SkillListParams,
        SkillListResponse,
        SessionCreateParams,
        SessionCreateResponse,
        SessionListParams,
        SessionListResponse,
        SessionReadParams,
        SessionReadResponse,
        SessionResumeParams,
        SessionResumeResponse,
        SessionInputParams,
        SessionInputResponse,
        SessionBtwParams,
        SessionHandoffParams,
        BtwEvent,
        SessionInterruptParams,
        SessionInterruptResponse,
        RequestResolveParams,
        RequestResolveResponse,
        SessionUpdateParams,
        SessionUpdateResponse,
        SessionCompactParams,
        SessionCompactResponse,
        SessionCloseParams,
        SessionCloseResponse,
        EventsParams,
        EventsResponse,
    );
    let schema = serde_json::json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "Canter protocol type catalog",
        "$defs": schemas.definitions(),
    });
    let mut json = serde_json::to_string_pretty(&schema)?;
    json.push('\n');
    fs::write(directory.join("protocol.schema.json"), json)?;
    fs::write(
        directory.join("typescript/version.ts"),
        format!(
            "// Generated by export_protocol; do not edit.\nexport const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n"
        ),
    )?;
    normalize_whitespace(config.out_dir())?;
    Ok(())
}

fn normalize_whitespace(directory: &Path) -> std::io::Result<()> {
    for entry in fs::read_dir(directory)? {
        let path = entry?.path();
        if path.is_dir() {
            normalize_whitespace(&path)?;
        } else if path.extension().is_some_and(|extension| extension == "ts") {
            let text = fs::read_to_string(&path)?;
            let normalized = text
                .lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n");
            fs::write(path, normalized + "\n")?;
        }
    }
    Ok(())
}

fn export_type<T: JsonSchema + TS + 'static>(
    schemas: &mut SchemaGenerator,
    config: &Config,
) -> Result<(), Box<dyn std::error::Error>> {
    let _ = schemas.subschema_for::<T>();
    T::export_all(config)?;
    Ok(())
}
